#!/bin/sh
# Install or remove the pre-commit hook of this repository.
#   sh scripts/git-hooks/install.sh install     (make hooks)
#   sh scripts/git-hooks/install.sh uninstall   (make unhooks)
#
# The hook is copied into the hooks directory of the repository (.git/hooks).
# Copying, instead of pointing core.hooksPath at this tracked directory, keeps
# three things true: Git never runs a file straight out of a checked-out
# branch, other hooks in .git/hooks keep working, and the hook also exists on
# branches that do not have this directory.
set -u

action=${1:-install}
source_hook=$(dirname "$0")/pre-commit
mark='devcontainer-python pre-commit hook'

if ! common=$(git rev-parse --git-common-dir 2>/dev/null); then
    echo 'Git リポジトリではないため、何もしませんでした。'
    exit 0
fi
hooks="$common/hooks"
target="$hooks/pre-commit"
backup="$hooks/pre-commit.before-devcontainer"

is_ours() { [ -f "$1" ] && grep -q "$mark" "$1"; }
# The hook written by `prek install` / `pre-commit install`; it is replaced.
is_generated() { [ -f "$1" ] && grep -Eq 'generated by (prek|pre-commit)' "$1"; }

# Where Git looks for hooks. A core.hooksPath from ~/.gitconfig (which VS Code
# copies into the container) would make Git ignore .git/hooks altogether.
hooks_path=$(git config --get core.hooksPath 2>/dev/null)
local_hooks_path=$(git config --local --get core.hooksPath 2>/dev/null)

case $action in
    install)
        mkdir -p "$hooks" || exit 1
        if [ -e "$target" ] && ! is_ours "$target" && ! is_generated "$target"; then
            if [ -e "$backup" ]; then
                echo "既存のフック $target を置き換えられません（退避先 $backup が既にあります）。" >&2
                echo '中身を確認して、不要なほうを削除してから、もう一度実行してください。' >&2
                exit 1
            fi
            mv "$target" "$backup" || exit 1
            echo "既存のフックを $backup に退避しました（make unhooks で元に戻ります）。"
        fi
        cp "$source_hook" "$target" && chmod +x "$target" || exit 1
        # The previous version of `make hooks` registered the tracked directory.
        if [ "$local_hooks_path" = scripts/git-hooks ]; then
            git config --local --unset-all core.hooksPath
            hooks_path=$(git config --get core.hooksPath 2>/dev/null)
        fi
        if [ -n "$hooks_path" ]; then
            # Only this repository: use its own hooks directory again.
            git config --local core.hooksPath .git/hooks || exit 1
            echo "core.hooksPath（$hooks_path）が設定されていたため、このリポジトリだけ .git/hooks を使う設定にしました。"
        fi
        echo "コミット前フックを登録しました（$target）。"
        ;;
    uninstall)
        if is_ours "$target"; then
            rm -f "$target" || exit 1
            if [ -e "$backup" ]; then
                mv "$backup" "$target" && echo "退避していた既存のフックを $target に戻しました。"
            fi
            echo 'コミット前フックの登録を外しました。'
        else
            echo 'コミット前フックは登録されていません。'
        fi
        case $local_hooks_path in
            .git/hooks | scripts/git-hooks)
                git config --local --unset-all core.hooksPath
                echo 'このリポジトリの core.hooksPath の設定を外しました。'
                ;;
        esac
        ;;
    *)
        echo "使い方: $0 install|uninstall" >&2
        exit 2
        ;;
esac
